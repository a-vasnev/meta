%% Likelihood and covariance helpers
function residual = err(y, X, V, tau2)
%ERR Residuals for the base covariance model.
    beta_hat = inv(X' * inv(Omega(V,tau2)) * X) * ...
               (X' * inv(Omega(V,tau2)) * y);
    residual = y - X*beta_hat;
end

function residual = err1(y, X, V, tau2, rho)
%ERR1 Residuals for the alternative autocorrelation model.
    beta_hat = inv(X' * inv(Omega1(V,tau2,rho)) * X) * ...
               (X' * inv(Omega1(V,tau2,rho)) * y);
    residual = y - X*beta_hat;
end

function covariance = Omega(V, tau2)
%OMEGA Add independent between-study variance to sampling covariance.
    covariance = tau2*eye(size(V,1)) + V;
end

function covariance = Omega1(V, tau2, rho)
%OMEGA1 Apply AR(1)-style correlation to the between-study component.
    k = size(V,1);
    P_ac = eye(k);
    for j = 1:k-1
        P_ac = P_ac + rho^j * ...
               (diag(ones(k-j,1),j) + diag(ones(k-j,1),-j));
    end
    covariance = tau2*P_ac + V;
end

function likelihood = phi_tau(y, X, V, tau2)
%PHI_TAU Concentrated Gaussian log-likelihood kernel.
    residual = err(y, X, V, tau2);
    quadratic_form = residual' * inv(Omega(V,tau2)) * residual;
    likelihood = -(log(det(Omega(V,tau2))) + quadratic_form);
end

function likelihood = phi_tau1(y, X, V, tau2, rho)
%PHI_TAU1 Kernel for the alternative autocorrelation specification.
    residual = err1(y, X, V, tau2, rho);
    quadratic_form = residual' * inv(Omega1(V,tau2,rho)) * residual;
    likelihood = -(log(det(Omega1(V,tau2,rho))) + quadratic_form);
end

function covariance = V_ec(V, rho)
%V_EC Equicorrelated sampling covariance matrix.
    k = size(V,1);
    P = (ones(k,k)-eye(k))*rho + eye(k);
    root_V = sqrtm(V);
    covariance = root_V*P*root_V;
end

function covariance = V_ac(V, rho)
%V_AC AR(1)-style sampling covariance matrix.
    k = size(V,1);
    P_ac = eye(k);
    for j = 1:k-1
        P_ac = P_ac + rho^j * ...
               (diag(ones(k-j,1),j) + diag(ones(k-j,1),-j));
    end
    root_V = sqrtm(V);
    covariance = root_V*P_ac*root_V;
end
